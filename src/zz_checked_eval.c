#include "zz_checked_internal.h"
#include <inttypes.h>
static zz_status ready(zz_context *c, FILE *out) {
    if (!c || !out)
        return ZZ_INVALID;
    memset(&c->error, 0, sizeof(c->error));
    if (c->draft || c->live->module[0])
        return zc_error(c, ZZ_CONFLICT, 0, 0, "unclosed patch or module");
    return ZZ_OK;
}
zz_status zz_context_run(zz_context *c, FILE *out) {
    int64_t *values = NULL, *vars = NULL, *printed = NULL;
    size_t i, nprint = 0;
    zz_status status = ready(c, out);
    zc_state *s;
    if (status != ZZ_OK)
        return status;
    s = c->live;
    values = calloc(s->nnodes + 1, sizeof(*values));
    vars = calloc(s->nsymbols + 1, sizeof(*vars));
    printed = calloc(s->nstatements + 1, sizeof(*printed));
    if (!values || !vars || !printed) {
        status = zc_error(c, ZZ_NOMEM, 0, 0, "allocation failed");
        goto done;
    }
    /* Nodes are topologically ordered in statement order. No recursion or effects
     * during evaluation; output is flushed only after ALL arithmetic succeeds. */
    for (i = 0; i < s->nnodes; i++) {
        zc_node *n = &s->nodes[i];
        int ok = 1;
        switch (n->kind) {
        case ZC_CONST:
            values[i] = n->value;
            break;
        case ZC_LOAD:
            values[i] = vars[n->a];
            break;
        case ZC_ADD:
            ok = zz_i64_add(values[n->a], values[n->b], &values[i]);
            break;
        case ZC_SUB:
            ok = zz_i64_sub(values[n->a], values[n->b], &values[i]);
            break;
        case ZC_MUL:
            ok = zz_i64_mul(values[n->a], values[n->b], &values[i]);
            break;
        case ZC_ASSIGN:
            vars[n->a] = values[n->b];
            break;
        case ZC_PRINT:
            printed[nprint++] = values[n->a];
            break;
        }
        if (!ok) {
            status = zc_error(c, ZZ_INVALID, 0, 0, "i64 overflow at AST node %zu", i);
            goto done;
        }
    }
    for (i = 0; i < nprint; i++)
        if (fprintf(out, "%" PRId64 "\n", printed[i]) < 0) {
            status = zc_error(c, ZZ_INVALID, 0, 0, "output write failed");
            break;
        }
    if (status == ZZ_OK && fflush(out))
        status = zc_error(c, ZZ_INVALID, 0, 0, "output flush failed");
done:
    free(values);
    free(vars);
    free(printed);
    return status;
}
zz_status zz_context_emit_c(zz_context *c, FILE *out) {
    size_t i, prints = 0;
    zc_state *s;
    zz_status status = ready(c, out);
    if (status != ZZ_OK)
        return status;
    s = c->live;
    /* Portable C11; generated identifiers derive from stable indices, never source
     * spelling. Helpers reproduce zz_i64_* semantics without compiler intrinsics. */
    fputs("/* Generated by OpenZz checked profile. */\n#include <stdint.h>\n#include "
          "<inttypes.h>\n#include <stdio.h>\n#include <stdlib.h>\n",
          out);
    fputs("static void overflow(void) { fputs(\"i64 overflow\\n\",stderr); exit(1); }\n", out);
    fputs("static int64_t add(int64_t a,int64_t b) { if((b>0 && a>INT64_MAX-b)||(b<0 && "
          "a<INT64_MIN-b)) overflow(); return a+b; }\n",
          out);
    fputs("static int64_t sub(int64_t a,int64_t b) { if((b>0 && a<INT64_MIN+b)||(b<0 && "
          "a>INT64_MAX+b)) overflow(); return a-b; }\n",
          out);
    fputs("static int64_t mul(int64_t a,int64_t b) { if(a>0 ? ((b>0 && a>INT64_MAX/b)||(b<0 && "
          "b<INT64_MIN/a)) : (a<0 && ((b>0 && a<INT64_MIN/b)||(b<0 && a<INT64_MAX/b)))) "
          "overflow(); return a*b; }\n",
          out);
    fprintf(out,
            "int main(void) {\n  static int64_t v[%zu]={0}, n[%zu]={0};\n  (void)v; (void)n; (void)add; "
            "(void)sub; (void)mul;\n",
            s->nsymbols + 1, s->nnodes + 1);
    for (i = 0; i < s->nnodes; i++) {
        zc_node *n = &s->nodes[i];
        switch (n->kind) {
        case ZC_CONST:
            if (n->value == INT64_MIN)
                fprintf(out, "  n[%zu]=INT64_MIN;\n", i);
            else
                fprintf(out, "  n[%zu]=%sINT64_C(%" PRId64 ");\n", i, n->value < 0 ? "-" : "",
                        n->value < 0 ? -n->value : n->value);
            break;
        case ZC_LOAD:
            fprintf(out, "  n[%zu]=v[%zu];\n", i, n->a);
            break;
        case ZC_ADD:
        case ZC_SUB:
        case ZC_MUL:
            fprintf(out, "  n[%zu]=%s(n[%zu],n[%zu]);\n", i,
                    n->kind == ZC_ADD   ? "add"
                    : n->kind == ZC_SUB ? "sub"
                                        : "mul",
                    n->a, n->b);
            break;
        case ZC_ASSIGN:
            fprintf(out, "  v[%zu]=n[%zu];\n", n->a, n->b);
            break;
        case ZC_PRINT:
            prints++;
            break;
        }
    }
    if (prints)
        for (i = 0; i < s->nnodes; i++)
            if (s->nodes[i].kind == ZC_PRINT)
                fprintf(out, "  if(printf(\"%%\" PRId64 \"\\n\",n[%zu])<0) return 1;\n",
                        s->nodes[i].a);
    fputs("  return fflush(stdout) ? 1 : 0;\n}\n", out);
    if (ferror(out) || fflush(out))
        return zc_error(c, ZZ_INVALID, 0, 0, "C output write failed");
    return ZZ_OK;
}
